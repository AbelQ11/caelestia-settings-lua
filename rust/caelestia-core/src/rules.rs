//! Parsing of Hyprland rules.conf into window rules.
//!
//! Pure string-in / data-out functions: no file I/O here, so everything
//! is unit-testable without touching the filesystem. Thin I/O wrappers
//! come later, together with the PyO3 bindings.

/// A single `windowrule = ...` entry extracted from rules.conf.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WindowRule {
    pub rule: String,
    pub match_type: String,
    pub match_val: String,
    pub raw: String,
    pub managed: bool,
}

/// Marks the start of the block this app owns; every rule on or after this
/// line is `managed = true` so the UI knows it is allowed to rewrite it.
/// The marker line itself is skipped, not emitted as a rule.
const MANAGED_MARKER: &str = "# Auto-generated by Caelestia Settings – Window Rules";
const MANAGED_MARKER_LUA: &str = "-- Auto-generated by Caelestia Settings – Window Rules";

/// Parses all window rules from rules.conf or rules.lua content.
pub fn parse_rules_conf(input: &str) -> Vec<WindowRule> {
    let mut result = Vec::new();
    let mut in_managed = false;

    // Check if file uses Lua syntax
    if input.contains("hl.window_rule") || input.contains("tagged_rule") {
        for raw_line in input.lines() {
            let line = raw_line.trim();
            if line == MANAGED_MARKER || line == MANAGED_MARKER_LUA {
                in_managed = true;
                continue;
            }
            if line.is_empty() || line.starts_with("--") || line.starts_with('#') {
                continue;
            }

            if line.contains("hl.window_rule") {
                if let Some(rules) = parse_lua_window_rule(line, in_managed) {
                    result.extend(rules);
                }
            } else if line.starts_with("windowrule") {
                if let Some(rule) = parse_conf_windowrule_line(line, in_managed) {
                    result.push(rule);
                }
            }
        }
        return result;
    }

    for raw_line in input.lines() {
        let line = raw_line.trim();

        if line == MANAGED_MARKER || line == MANAGED_MARKER_LUA {
            in_managed = true;
            continue;
        }
        if line.is_empty() || line.starts_with('#') || line.starts_with("--") {
            continue;
        }
        if !line.starts_with("windowrule") {
            continue;
        }

        if let Some(rule) = parse_conf_windowrule_line(line, in_managed) {
            result.push(rule);
        }
    }

    result
}

fn parse_conf_windowrule_line(line: &str, in_managed: bool) -> Option<WindowRule> {
    let (_, rest) = line.split_once('=')?;
    let rest = rest.trim();

    let (rule_part, match_type, match_val) = match rest.rfind(", match:") {
        Some(idx) => {
            let rule_part = &rest[..idx];
            let match_part = rest[idx + ", match:".len()..].trim();

            let mut tokens = match_part.splitn(2, char::is_whitespace);
            let match_type = tokens.next().filter(|s| !s.is_empty()).unwrap_or("class");
            let match_val = tokens.next().unwrap_or("").trim_start();
            (rule_part, match_type, match_val)
        }
        None => (rest, "", ""),
    };

    Some(WindowRule {
        rule: rule_part.trim().to_string(),
        match_type: match_type.to_string(),
        match_val: match_val.to_string(),
        raw: line.to_string(),
        managed: in_managed,
    })
}

fn parse_lua_window_rule(line: &str, in_managed: bool) -> Option<Vec<WindowRule>> {
    // Extract match table: match = { ... }
    let mut match_type = "class".to_string();
    let mut match_val = String::new();

    if let Some(m_idx) = line.find("match") {
        let after_match = &line[m_idx..];
        if let Some(open) = after_match.find('{') {
            if let Some(close) = after_match[open..].find('}') {
                let match_inner = &after_match[open + 1..open + close];
                for part in match_inner.split(',') {
                    let part = part.trim();
                    if let Some((k, v)) = part.split_once('=') {
                        let k = k.trim();
                        let v = v.trim().trim_matches(|c| c == '"' || c == '\'');
                        if k == "class" || k == "title" || k == "initial_title" || k == "initial_class" {
                            match_type = k.to_string();
                            match_val = v.to_string();
                            break;
                        }
                    }
                }
            }
        }
    }

    if match_val.is_empty() {
        return None;
    }

    let mut rules = Vec::new();

    // Check workspace
    if let Some(ws_idx) = line.find("workspace") {
        let after_ws = &line[ws_idx..];
        if let Some((_, v)) = after_ws.split_once('=') {
            let mut val = v.trim();
            if let Some(comma) = val.find(',') {
                val = &val[..comma].trim();
            }
            if let Some(brace) = val.find('}') {
                val = &val[..brace].trim();
            }
            let val = val.trim_matches(|c| c == '"' || c == '\'');
            if !val.is_empty() {
                rules.push(WindowRule {
                    rule: format!("workspace {val}"),
                    match_type: match_type.clone(),
                    match_val: match_val.clone(),
                    raw: line.to_string(),
                    managed: in_managed,
                });
            }
        }
    }

    // Check float
    if line.contains("float = true") || line.contains("float = 1") {
        rules.push(WindowRule {
            rule: "float true".to_string(),
            match_type: match_type.clone(),
            match_val: match_val.clone(),
            raw: line.to_string(),
            managed: in_managed,
        });
    }

    if rules.is_empty() {
        // Fallback for general rule
        rules.push(WindowRule {
            rule: "custom".to_string(),
            match_type,
            match_val,
            raw: line.to_string(),
            managed: in_managed,
        });
    }

    Some(rules)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_rule_without_match() {
        let rules = parse_rules_conf("windowrule = float, class:^(kitty)$");
        assert_eq!(rules.len(), 1);
        assert_eq!(rules[0].rule, "float, class:^(kitty)$");
        assert_eq!(rules[0].match_type, "");
        assert_eq!(rules[0].match_val, "");
        assert!(!rules[0].managed);
    }

    #[test]
    fn parses_rule_with_match() {
        let rules =
            parse_rules_conf("windowrule = workspace special:music, match: class feishin|Spotify");
        assert_eq!(rules.len(), 1);
        assert_eq!(rules[0].rule, "workspace special:music");
        assert_eq!(rules[0].match_type, "class");
        assert_eq!(rules[0].match_val, "feishin|Spotify");
    }

    #[test]
    fn splits_match_on_last_occurrence_only() {
        let rules = parse_rules_conf("windowrule = float, match: literally, match: class Spotify");
        assert_eq!(rules[0].rule, "float, match: literally");
        assert_eq!(rules[0].match_type, "class");
        assert_eq!(rules[0].match_val, "Spotify");
    }

    #[test]
    fn empty_match_part_defaults_type_to_class() {
        let rules = parse_rules_conf("windowrule = float, match:   ");
        assert_eq!(rules[0].match_type, "class");
        assert_eq!(rules[0].match_val, "");
    }

    #[test]
    fn extra_whitespace_between_match_tokens_is_trimmed() {
        let rules = parse_rules_conf("windowrule = float, match:    class     Spotify");
        assert_eq!(rules[0].match_type, "class");
        assert_eq!(rules[0].match_val, "Spotify");
    }

    #[test]
    fn marker_line_toggles_managed_but_is_not_a_rule() {
        let input = "\
windowrule = float, class:^(before)$
# Auto-generated by Caelestia Settings – Window Rules
windowrule = float, class:^(after)$
";
        let rules = parse_rules_conf(input);
        assert_eq!(rules.len(), 2);
        assert!(!rules[0].managed);
        assert!(rules[1].managed);
    }

    #[test]
    fn skips_blank_lines_comments_and_non_windowrule_lines() {
        let input = "

# just a comment
bind = SUPER, T, exec, kitty
windowrule = float, class:^(kitty)$
";
        let rules = parse_rules_conf(input);
        assert_eq!(rules.len(), 1);
    }

    #[test]
    fn parses_lua_window_rules() {
        let input = r#"
hl.window_rule({ match = { class = "firefox" }, workspace = "2" })
-- Auto-generated by Caelestia Settings – Fenster-Regeln
hl.window_rule({ match = { class = "org.caelestia.settings" }, float = true })
"#;
        let rules = parse_rules_conf(input);
        assert_eq!(rules.len(), 2);
        assert_eq!(rules[0].match_val, "firefox");
        assert_eq!(rules[0].rule, "workspace 2");
        assert!(!rules[0].managed);
        assert_eq!(rules[1].match_val, "org.caelestia.settings");
        assert_eq!(rules[1].rule, "float true");
        assert!(rules[1].managed);
    }

    #[test]
    fn raw_preserves_trimmed_original_line() {
        let rules = parse_rules_conf("   windowrule = float, class:^(kitty)$   ");
        assert_eq!(rules[0].raw, "windowrule = float, class:^(kitty)$");
    }

    #[test]
    fn skips_malformed_line_without_equals_sign() {
        let input = "\
windowrule float, class:^(kitty)$
windowrule = float, class:^(after)$
";
        let rules = parse_rules_conf(input);
        assert_eq!(rules.len(), 1);
        assert_eq!(rules[0].rule, "float, class:^(after)$");
    }
}
