from src.pages import monitor, workspaces, window_rules


def _monitor(name, output, **kwargs):
    class Monitor:
        pass

    item = Monitor()
    item.name = name
    item.file_output = output
    item.description = output.removeprefix("desc:")
    item.disabled = False
    item.resolution = "2560x1600"
    item.hz = "240.000"
    item.x = 0
    item.y = 0
    item.scale = 1.0
    item.bitdepth = ""
    item.transform = "0"
    item.cm = ""
    item.vrr = False
    item.mirror = ""
    item.extra_fields = {"output": output, **kwargs}
    return item


def test_monitor_save_preserves_other_content(monkeypatch, tmp_path):
    target = tmp_path / "monitors.lua"
    target.write_text(
        """-- Generated by Monique

hl.monitor({
    output = "desc:AU Optronics 0x5AB1",
    mode = "2560x1600@240",
    position = "0x0",
    scale = 1.25,
    cm = "srgb",
    sdr_min_luminance = 0.2,
})

hl.workspace_rule({ workspace = "1", monitor = "desc:AU Optronics 0x5AB1", default = true })
"""
    )
    monkeypatch.setattr(monitor, "HYPR_MONITORS_LUA", target)
    monkeypatch.setattr(monitor, "HYPR_HYPRLAND_DIR", tmp_path / "hyprland")
    monkeypatch.setattr(
        monitor.backup, "atomic_write_text", lambda path, text, **kwargs: path.write_text(text)
    )

    item = _monitor("eDP-1", "desc:AU Optronics 0x5AB1", cm="srgb", sdr_min_luminance=0.2)
    item.x = 1920
    item.scale = 1.25
    monitor._save_monitors_conf([item])

    saved = target.read_text()
    assert 'output = "desc:AU Optronics 0x5AB1"' in saved
    assert 'position = "1920x0"' in saved
    assert 'cm = "srgb"' in saved
    assert "sdr_min_luminance = 0.2" in saved
    assert 'workspace = "1"' in saved
    assert "-- Generated by Monique" in saved


def test_workspace_save_keeps_monitors(monkeypatch, tmp_path):
    target = tmp_path / "monitors.lua"
    target.write_text(
        """hl.monitor({ output = "eDP-1", mode = "2560x1600@240", position = "0x0", scale = 1 })

-- old rule
hl.workspace_rule({ workspace = "9", monitor = "eDP-1" })
"""
    )
    monkeypatch.setattr(workspaces, "HYPR_MONITORS_LUA", target)
    monkeypatch.setattr(
        workspaces.apply, "write_and_reload", lambda path, text, **kwargs: path.write_text(text)
    )

    workspaces._save_workspaces([
        {"number": 1, "workspace": "1", "monitor": "eDP-1", "default": True, "persistent": False},
    ])

    saved = target.read_text()
    assert 'hl.monitor({ output = "eDP-1"' in saved
    assert 'workspace = "1"' in saved
    assert 'workspace = "9"' not in saved
    assert "BEGIN Caelestia Settings: workspace rules" in saved


def test_window_rules_save_uses_managed_block(monkeypatch, tmp_path):
    target = tmp_path / "hypr-user.lua"
    target.write_text(
        """local config = {}

-- Auto-generated by Caelestia Settings – Fenster-Regeln
hl.window_rule({ match = { class = "old" }, float = true })

return config
"""
    )
    monkeypatch.setattr(window_rules, "HYPR_USER_LUA", target)
    monkeypatch.setattr(
        window_rules.apply, "write_and_reload", lambda path, text, **kwargs: path.write_text(text)
    )

    window_rules._write_rules_conf([
        'hl.window_rule({ match = { class = "firefox" }, workspace = "2" })',
    ])

    saved = target.read_text()
    assert "BEGIN Caelestia Settings: window rules" in saved
    assert 'class = "firefox"' in saved
    assert 'class = "old"' not in saved
    assert saved.index("BEGIN Caelestia Settings") < saved.index("return config")
    assert "Fenster-Regeln" not in saved
