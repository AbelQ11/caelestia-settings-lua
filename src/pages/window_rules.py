class AppRuleRow(Adw.ActionRow):
    def __init__(self, app_info: dict, saved_settings: dict,
                 workspace_options: list[tuple[str, str]], on_change_cb):
        super().__init__()
        self._wm_class    = app_info["wm_class"]
        self._is_web_app  = app_info.get("is_web_app", False)
        self._cb          = on_change_cb
        self._advanced = {
            "fullscreen": saved_settings.get("fullscreen", "default"),
            "idle_inhibit": saved_settings.get("idle_inhibit", "default"),
            **{
                field: bool(saved_settings.get(field, False))
                for field, _label in ADVANCED_SWITCHES
            },
            **{
                field: str(saved_settings.get(field, ""))
                for field, _label, _placeholder in ADVANCED_TEXTS
            },
        }


        self.set_title(app_info["name"])
        sub = app_info["wm_class"] or t("Unknown class")
        if self._is_web_app: sub += "  •  Web app"
        self.set_subtitle(sub)

        # Icon
        icon = Gtk.Image(); icon.set_pixel_size(32)
        icon_name = app_info.get("icon", "")
        theme = Gtk.IconTheme.get_for_display(icon.get_display()) if icon.get_display() else None
        if theme and icon_name and theme.has_icon(icon_name):
            icon.set_from_icon_name(icon_name)
        else:
            icon.set_from_icon_name("application-x-executable")
        icon.set_margin_end(8)
        self.add_prefix(icon)

        def _make_suffix(label_text, combo_options, saved_key, default_val):
            vbox = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=2)
            vbox.set_valign(Gtk.Align.CENTER)
            lbl = Gtk.Label(label=label_text)
            lbl.add_css_class("caption"); lbl.set_halign(Gtk.Align.START)
            vbox.append(lbl)
            combo = Gtk.ComboBoxText()
            for opt_id, opt_lbl in combo_options:
                combo.append(opt_id, opt_lbl)
            combo.set_active_id(saved_settings.get(saved_key, default_val))
            combo.connect("changed", lambda _: self._cb())
            vbox.append(combo)
            self.add_suffix(vbox)
            return combo

        default_match = "initial_title" if self._is_web_app else "class"
        self.match_combo = _make_suffix("Match",     MATCH_TYPE_OPTIONS, "match_type", default_match)
        self.ws_combo    = _make_suffix("Workspace", workspace_options,  "workspace",  "default")
        self.float_combo = _make_suffix(t("Behavior"), FLOAT_OPTIONS,      "float",      "default")

        advanced_btn = Gtk.Button()
        advanced_btn.set_icon_name("emblem-system-symbolic")
        advanced_btn.add_css_class("flat")
        advanced_btn.set_valign(Gtk.Align.CENTER)
        advanced_btn.set_tooltip_text(t("Advanced window rule options"))
        advanced_btn.connect("clicked", lambda _b: self._open_advanced())
        self.add_suffix(advanced_btn)

        # Remember the initial state for change detection
        self._initial_state = self._current_state()

    def _current_state(self) -> dict:
        return {
            "match_type": self.match_combo.get_active_id() or "class",
            "workspace":  self.ws_combo.get_active_id()    or "default",
            "float":      self.float_combo.get_active_id() or "default",
            **self._advanced,
        }

    def is_user_modified(self) -> bool:
        """True when the user changed at least one value."""
        return self._current_state() != self._initial_state

    def get_rule(self) -> tuple[str, dict]:
        return self._wm_class, self._current_state()

    def _open_advanced(self):
        dialog = Adw.MessageDialog(
            transient_for=self.get_root(),
            heading=t("Advanced window rule options"),
            body=t("Leave empty/default to keep Hyprland's normal behaviour."),
        )
        box = Gtk.ListBox()
        box.set_selection_mode(Gtk.SelectionMode.NONE)
        box.add_css_class("boxed-list")

        fullscreen_row = Adw.ActionRow(title=t("Fullscreen"))
        fullscreen = Gtk.ComboBoxText()
        fullscreen.set_valign(Gtk.Align.CENTER)
        for value, label in FULLSCREEN_OPTIONS:
            fullscreen.append(value, label)
        fullscreen.set_active_id(self._advanced.get("fullscreen", "default"))
        fullscreen_row.add_suffix(fullscreen)
        box.append(fullscreen_row)

        idle_row = Adw.ActionRow(title=t("Idle inhibit"))
        idle_inhibit = Gtk.ComboBoxText()
        idle_inhibit.set_valign(Gtk.Align.CENTER)
        for value, label in IDLE_INHIBIT_OPTIONS:
            idle_inhibit.append(value, label)
        idle_inhibit.set_active_id(self._advanced.get("idle_inhibit", "default"))
        idle_row.add_suffix(idle_inhibit)
        box.append(idle_row)

        switches = {}
        for field, label in ADVANCED_SWITCHES:
            row = Adw.SwitchRow(title=label)
            row.set_active(bool(self._advanced.get(field, False)))
            box.append(row)
            switches[field] = row

        entries = {}
        for field, label, placeholder in ADVANCED_TEXTS:
            row = Adw.EntryRow(title=label)
            row.set_text(str(self._advanced.get(field, "")))
            row.set_tooltip_text(placeholder)
            box.append(row)
            entries[field] = row

        dialog.set_extra_child(box)
        dialog.add_response("cancel", t("Cancel"))
        dialog.add_response("save", t("Save"))
        dialog.set_response_appearance("save", Adw.ResponseAppearance.SUGGESTED)

        def on_response(dialog_obj, response):
            if response != "save":
                return
            self._advanced.update(
                {
                    "fullscreen": fullscreen.get_active_id() or "default",
                    "idle_inhibit": idle_inhibit.get_active_id() or "default",
                    **{field: widget.get_active() for field, widget in switches.items()},
                    **{field: widget.get_text().strip() for field, widget in entries.items()},
                }
            )
            self._cb()

        dialog.connect("response", on_response)
        dialog.present()