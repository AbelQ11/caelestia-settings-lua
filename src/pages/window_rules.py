LEGACY_MANAGED_MARKERS = (
    "-- Auto-generated by Caelestia Settings – Fenster-Regeln",
    "-- Auto-generated by Caelestia Settings – Window Rules",
    "# Auto-generated by Caelestia Settings – Fenster-Regeln",
)


def _generate_rules_lines(rules: dict) -> list[str]:
    lines = []
    for key, settings in rules.items():
        if not key: continue
        workspace  = settings.get("workspace",  "default")
        float_val  = settings.get("float",      "default")
        match_type = settings.get("match_type", "class")

        props = []
        if workspace != "default":
            props.append(f'workspace = "{workspace}"')
        if float_val != "default":
            val_bool = "true" if str(float_val).lower() in ("true", "1") else "false"
            props.append(f"float = {val_bool}")

        if settings.get("fullscreen", "default") != "default":
            props.append(f'fullscreen = {settings["fullscreen"]}')
        for field, _label in ADVANCED_SWITCHES:
            if settings.get(field):
                props.append(f"{field} = true")
        if settings.get("idle_inhibit", "default") != "default":
            props.append(f'idle_inhibit = "{settings["idle_inhibit"]}"')
        for field, _label, _placeholder in ADVANCED_TEXTS:
            value = str(settings.get(field, "")).strip()
            if value:
                props.append(f'{field} = "{value}"')

        if props:
            props_str = ", ".join(props)
            lines.append(f'hl.window_rule({{ match = {{ {match_type} = "{key}" }}, {props_str} }})')
    return lines


def _write_rules_conf(new_lines: list[str]):
    target = HYPR_USER_LUA
    target.parent.mkdir(parents=True, exist_ok=True)
    raw = read_text(target)
    if not raw.strip():
        raw = "local config = {}\n\nreturn config\n"

    # Remove blocks written by older versions of the app.
    for marker in LEGACY_MANAGED_MARKERS:
        index = raw.find(marker)
        if index < 0:
            continue
        anchor = raw.find("return config", index)
        raw = raw[:index] + (raw[anchor:] if anchor >= 0 else "")

    body = "\n".join(new_lines)
    if body:
        raw = lua.replace_managed_block(raw, BLOCK_RULES, body)
    else:
        raw = lua.remove_managed_block(raw, BLOCK_RULES)

    apply.write_and_reload(target, raw)


_write_rules_lua = _write_rules_conf


