"""Workspace rule editor.

Rules are written as ``hl.workspace_rule`` blocks into the managed section of
``~/.config/hypr/monitors.lua``.  Monitor definitions and anything else in the
file are preserved.  Changes are applied with ``hyprctl reload`` (never by
passing Lua source to ``hyprctl keyword``).
"""

from __future__ import annotations

import json
import subprocess

from gi.repository import Adw, GLib, Gtk

from src import apply, backup, lua
from src.config import (
    HYPR_MONITORS_LUA,
    parse_monitors_conf,
    read_text,
)
from src.lang import t

WORKSPACE_BLOCK = "workspace rules"
LEGACY_MARKER = "# Workspaces – Auto-generated by Caelestia Settings"


def _load_workspaces() -> list[dict]:
    """Numeric workspace rules from the active Hyprland config."""

    data = parse_monitors_conf()
    result = [
        {
            "workspace": str(ws["workspace"]),
            "number": ws["number"],
            "monitor": ws.get("monitor", ""),
            "default": bool(ws.get("default", False)),
            "persistent": bool(ws.get("persistent", False)),
            "gaps_in": ws.get("gaps_in"),
            "gaps_out": ws.get("gaps_out"),
            "layout": ws.get("layout", ""),
            "no_rounding": bool(ws.get("no_rounding", False)),
            "no_border": bool(ws.get("no_border", False)),
            "no_shadow": bool(ws.get("no_shadow", False)),
            "decorate": bool(ws.get("decorate", True)),
        }
        for ws in data["workspaces"]
        if ws.get("number") is not None
    ]
    return sorted(result, key=lambda item: item["number"])


def _get_monitor_names() -> list[str]:
    try:
        res = subprocess.run(
            ["hyprctl", "monitors", "-j"],
            capture_output=True, text=True, check=True, timeout=3,
        )
        return [monitor["name"] for monitor in json.loads(res.stdout)]
    except (OSError, subprocess.SubprocessError, json.JSONDecodeError):
        data = parse_monitors_conf()
        return [monitor["name"] for monitor in data.get("monitors", [])]


def _build_workspace_line(ws: dict) -> str:
    workspace = str(ws.get("workspace") or ws.get("number") or "")
    fields: dict = {"workspace": workspace}
    if ws.get("monitor"):
        fields["monitor"] = ws["monitor"]
    if ws.get("default"):
        fields["default"] = True
    if ws.get("persistent"):
        fields["persistent"] = True
    if ws.get("gaps_in") not in (None, ""):
        fields["gaps_in"] = int(ws["gaps_in"])
    if ws.get("gaps_out") not in (None, ""):
        fields["gaps_out"] = int(ws["gaps_out"])
    if ws.get("layout"):
        fields["layout"] = ws["layout"]
    if ws.get("no_rounding"):
        fields["no_rounding"] = True
    if ws.get("no_border"):
        fields["no_border"] = True
    if ws.get("no_shadow"):
        fields["no_shadow"] = True
    if ws.get("decorate") is False:
        fields["decorate"] = False
    return f"hl.workspace_rule({lua.format_value(fields)})"


def _save_workspaces(workspaces: list[dict]) -> None:
    target = HYPR_MONITORS_LUA
    target.parent.mkdir(parents=True, exist_ok=True)
    text = read_text(target)

    # Remove existing workspace rules, wherever they lived in the file.
    calls = lua.iter_calls(text, {"hl.workspace_rule"})
    for call in reversed(calls):
        text = text[: call.start] + text[call.end:]

    text = lua.remove_managed_block(text, WORKSPACE_BLOCK)

    lines = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped == LEGACY_MARKER:
            continue
        # Legacy Hyprland .conf workspace lines
        if stripped.startswith("workspace") and "=" in stripped and "{" not in stripped:
            continue
        lines.append(line)
    text = "\n".join(lines).rstrip()

    body = "\n\n".join(_build_workspace_line(ws) for ws in sorted(workspaces, key=lambda w: w["number"]))
    if body:
        block = lua.managed_block(WORKSPACE_BLOCK, body)
        text = f"{text}\n\n{block}\n" if text else f"{block}\n"

    apply.write_and_reload(target, text)


